const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const { execFileSync, execFile } = require('node:child_process');
const { promisify } = require('node:util');
const delay = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
async function until(check, label, timeout = 12000) {
  const start = Date.now();
  while (Date.now() - start < timeout) { if (await check()) return; await delay(100); }
  throw new Error(`Timed out: ${label}`);
}
exports.run = async ({ app, mainWindow, overlay, dictation, store, clipboard }) => {
  const errors = [];
  mainWindow.webContents.on('console-message', event => { if (event.level === 'error') errors.push(event.message); });
  const js = source => mainWindow.webContents.executeJavaScript(source, true);
  const output = path.join(__dirname, '..', 'test-results');
  fs.mkdirSync(output, { recursive: true });
  const oldClipboard = { text: clipboard.readText(), html: clipboard.readHTML(), rtf: clipboard.readRTF(), image: clipboard.readImage() };
  const capture = async name => {
    mainWindow.showInactive();
    await js('document.fonts.ready.then(() => true)');
    await delay(250);
    const image = await mainWindow.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true });
    fs.writeFileSync(path.join(output, name), image.toPNG());
    mainWindow.hide();
  };
  try {
    await until(() => js('Boolean(document.querySelector("#groq-key"))'), 'connection setup ready');
    assert.equal(await js('document.title'), 'Cawal — Cangkem Virtual');
    assert.equal(await js('document.querySelectorAll(".navigation .tabs button").length'), 2);
    assert.equal(require('electron').globalShortcut.isRegistered(store.read().hotkey), true, 'a usable global shortcut is registered');
    await js('document.querySelectorAll(".tabs button")[0].click()');
    await until(() => js('Boolean(document.querySelector("#model"))'), 'general settings');
    assert.equal(await js('document.querySelector(".record-button, .transcript, .result-section") === null'), true, 'desktop is settings only');
    assert.equal(await js('document.querySelector("#model").options.length'), 2);
    assert.equal(store.read().language, 'id');
    assert.equal(await js('document.querySelector("#language") === null && document.querySelector(".settings-view").textContent.includes("Indonesia + English")'), true, 'Indonesian with English context replaces the language selector');
    const previousHotkey = store.read().hotkey;
    await js('document.querySelector(".shortcut-capture").click()');
    await until(() => js('document.querySelector(".shortcut-field").classList.contains("capturing")'), 'custom shortcut capture');
    assert.equal(require('electron').globalShortcut.isRegistered(previousHotkey), false, 'dictation shortcut suspended during capture');
    await js(`document.querySelector('#custom-shortcut').dispatchEvent(new KeyboardEvent('keydown', { key: 'k', code: 'KeyK', ctrlKey: true, shiftKey: true, bubbles: true, cancelable: true }))`);
    await until(() => js('Boolean(document.querySelector(".save-shortcut"))'), 'custom shortcut draft');
    assert.equal(require('electron').globalShortcut.isRegistered(previousHotkey), true, 'old shortcut restored before saving');
    await js('document.querySelector(".save-shortcut").click()');
    await until(() => store.read().hotkey === 'CommandOrControl+Shift+K', 'custom shortcut saved');
    assert.equal(require('electron').globalShortcut.isRegistered(store.read().hotkey), true);
    const persisted = JSON.parse(fs.readFileSync(path.join(app.getPath('userData'), 'settings.json'), 'utf8'));
    assert.equal(persisted.settings.hotkey, 'CommandOrControl+Shift+K');
    // Reject a combination already owned by a different action without losing the saved one.
    const electron = require('electron');
    assert.equal(electron.globalShortcut.register('Control+Alt+F11', () => {}), true);
    const conflict = await js(`(async () => window.cawal.saveSettings({ ...(await window.cawal.bootstrap()).value.settings, hotkey: 'CommandOrControl+Alt+F11' }))()`);
    assert.equal(conflict.ok, false);
    assert.equal(store.read().hotkey, 'CommandOrControl+Shift+K');
    assert.equal(electron.globalShortcut.isRegistered('CommandOrControl+Shift+K'), true);
    electron.globalShortcut.unregister('Control+Alt+F11');
    await js('document.querySelector(".shortcut-capture").click()');
    await until(() => js('document.querySelector(".shortcut-field").classList.contains("capturing")'), 'capture for cancellation');
    await js(`document.querySelector('#custom-shortcut').dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', code: 'Escape', bubbles: true, cancelable: true }))`);
    await until(() => js('!document.querySelector(".shortcut-field").classList.contains("capturing")'), 'capture cancelled');
    assert.equal(electron.globalShortcut.isRegistered('CommandOrControl+Shift+K'), true);
    await js('document.querySelectorAll(".tabs button")[1].click()');
    await until(() => js('Boolean(document.querySelector("#groq-key"))'), 'connection settings');
    await js(`(() => { const input = document.querySelector('#groq-key'); Object.getOwnPropertyDescriptor(HTMLInputElement.prototype, 'value').set.call(input, 'gsk_cawalSmokeTest000000000000'); input.dispatchEvent(new Event('input', { bubbles: true })); })()`);
    await until(() => js('!document.querySelector(".save-key").disabled'), 'key form ready');
    await js('document.querySelector(".save-key").click()');
    await until(() => store.hasKey(), 'key saved from settings');
    assert.equal(store.hasKey(), true);
    assert.equal(fs.readFileSync(path.join(app.getPath('userData'), 'settings.json'), 'utf8').includes('gsk_'), false);
    await until(() => js('document.querySelector("#groq-key").value === "" && !document.querySelector(".test-connection").disabled'), 'key input cleared');
    await js('document.querySelector(".test-connection").click()');
    await until(() => js('!document.querySelector(".test-connection").disabled'), 'connection test complete');
    assert.equal(await js('document.querySelector("[role=alert]") === null'), true, 'connection test succeeds');
    await capture('cawal-connection.png');
    await js('document.querySelectorAll(".tabs button")[0].click()');
    await until(() => js('Boolean(document.querySelector("#model"))'), 'general settings restored');
    await capture('cawal-general.png');
    // An internal test action exercises clipboard recovery; users start via shortcut.
    await js('window.cawal.action("toggle")');
    await until(() => dictation.snapshot().phase === 'recording', 'microphone recording');
    assert.equal(overlay.isVisible(), true);
    await delay(1200);
    await until(() => overlay.webContents.executeJavaScript('document.querySelector(".live-wave path").getBBox().height > 2'), 'Flow Line responds to microphone input');
    fs.writeFileSync(path.join(output, 'cawal-flow-line.png'), (await overlay.webContents.capturePage(undefined, { stayHidden: true, stayAwake: true })).toPNG());
    await js('window.cawal.action("toggle")');
    await until(() => dictation.snapshot().phase === 'done', 'transcription and cleanup');
    await until(() => overlay.webContents.executeJavaScript('document.querySelector(".live-wave path").getAttribute("d") === "M2 16 L62 16"'), 'Flow Line resets after recording');
    assert.equal(dictation.snapshot().result.text, 'Halo, ini pengujian Cawal.');
    assert.equal(dictation.snapshot().result.pasted, false);
    assert.equal(clipboard.readText(), 'Halo, ini pengujian Cawal.');
    await delay(150);
    assert.equal(await js('Boolean(document.querySelector(".recovery"))'), true, 'clipboard recovery available without transcript');
    await capture('cawal-recovery.png');
    await js('window.cawal.action("clear")');
    // Check the minimum supported desktop size and the reduced-motion preference.
    mainWindow.setSize(740, 560);
    await capture('cawal-compact.png');
    assert.equal(await js('document.documentElement.scrollWidth <= innerWidth'), true, 'no horizontal page overflow');
    mainWindow.setSize(820, 620);
    assert.equal(await js('getComputedStyle(document.documentElement).backgroundColor'), 'rgb(38, 42, 43)', 'Quiet Graphite surface');
    assert.equal(await js('getComputedStyle(document.querySelector(".shortcut-capture")).color'), 'rgb(255, 221, 51)');
    mainWindow.webContents.debugger.attach('1.3');
    await mainWindow.webContents.debugger.sendCommand('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] });
    assert.equal(await js('getComputedStyle(document.querySelector(".shortcut-capture")).transitionDuration'), '0s');
    mainWindow.webContents.debugger.detach();
    await js('window.cawal.action("clear")');
    await js('window.cawal.action("toggle")');
    await until(() => dictation.snapshot().phase === 'recording', 'second recording');
    await js('window.cawal.action("cancel")');
    assert.equal(dictation.snapshot().phase, 'idle');
    await delay(150);
    assert.equal(await js('Boolean(document.querySelector("#model")) && document.querySelector(".record-button") === null'), true);
    const fixture = path.join(output, 'native-paste-smoke.exe');
    const compiler = path.join(process.env.WINDIR, 'Microsoft.NET', 'Framework64', 'v4.0.30319', 'csc.exe');
    const backgroundFixture = path.join(output, 'background-dictation-smoke.exe');
    execFileSync(compiler, ['/nologo', '/target:exe', '/platform:x64', '/r:System.Windows.Forms.dll', '/r:System.Drawing.dll', `/out:${backgroundFixture}`, path.join(__dirname, '..', 'tests', 'BackgroundDictationSmoke.cs')], { windowsHide: true });
    mainWindow.hide();
    const overlayJs = source => overlay.webContents.executeJavaScript(source, true);
    await overlayJs('window.testLevels = []; window.cawal.onAudioLevel(level => window.testLevels.push(level)); true');
    const { screen } = electron;
    const pointerDisplay = screen.getDisplayNearestPoint(screen.getCursorScreenPoint());
    const targetDisplay = screen.getAllDisplays().find(display => display.id !== pointerDisplay.id) || pointerDisplay;
    const fixturePoint = screen.dipToScreenPoint({ x: targetDisplay.workArea.x + 24, y: targetDisplay.workArea.y + 24 });
    const backgroundRun = promisify(execFile)(backgroundFixture, [String(fixturePoint.x), String(fixturePoint.y)], { windowsHide: true, timeout: 18000 }).then(value => ({ value }), error => { console.error('Background fixture:', error.stdout || error.message); return { error }; });
    await until(() => dictation.snapshot().phase === 'recording', 'native shortcut starts background dictation');
    assert.equal(mainWindow.isVisible(), false);
    assert.equal(overlay.isVisible(), true);
    assert.equal(screen.getDisplayMatching(overlay.getBounds()).id, targetDisplay.id, 'wave follows the typing target monitor, independently of the mouse');
    assert.equal(overlay.isAlwaysOnTop(), true);
    console.log(`PASS: Overlay on target monitor; ${screen.getAllDisplays().length} displays, pointer and target differ: ${pointerDisplay.id !== targetDisplay.id}.`);
    await until(() => overlayJs('window.testLevels.filter(value => value > 0).length > 5'), 'real microphone levels reach overlay');
    assert.equal(await overlayJs('document.querySelectorAll(".live-wave path").length'), 1);
    assert.equal(await overlayJs('getComputedStyle(document.querySelector(".live-wave path")).stroke'), 'rgb(255, 221, 51)');
    assert.equal(await overlayJs('document.body.innerText.trim()'), '', 'icon overlay contains no visible text');
    assert.equal(await overlayJs('document.querySelectorAll("button").length'), 0, 'icon overlay contains no controls');
    assert.deepEqual(overlay.getSize(), [88, 56]);
    assert.equal(await overlayJs('document.documentElement.scrollWidth <= innerWidth'), true);
    const backgroundResult = await backgroundRun;
    if (backgroundResult.error) throw backgroundResult.error;
    console.log(backgroundResult.value.stdout.trim());
    assert.equal(dictation.snapshot().phase, 'done');
    assert.equal(dictation.snapshot().result.pasted, true);
    assert.equal(mainWindow.isVisible(), false);
    const stoppedLevelCount = await overlayJs('window.testLevels.length');
    await delay(300);
    assert.equal(await overlayJs('window.testLevels.length'), stoppedLevelCount, 'meter stops with recording');
    await until(() => !overlay.isVisible(), 'overlay hides after result');
    execFileSync(compiler, ['/nologo', '/target:exe', '/platform:x64', '/r:System.Windows.Forms.dll', '/r:System.Drawing.dll', `/out:${fixture}`, path.join(__dirname, '..', 'tests', 'NativePasteSmoke.cs')], { windowsHide: true });
    clipboard.writeText('Cawal native paste test');
    const native = await promisify(execFile)(fixture, [path.join(__dirname, '..', 'resources', 'bin', 'cawal-paste.exe')], { windowsHide: true, timeout: 12000 });
    console.log(native.stdout.trim());
    assert.deepEqual(errors, []);
    console.log('PASS: Settings-only navigation, key form and connection test, custom shortcut capture/save/conflict/cancel, Graphite palette, compact layout, reduced motion, encrypted key, fake microphone, Groq pipeline stub, clipboard recovery, cancellation and overlay.');
    console.log(`Screenshots: ${output}`);
    if (['Halo, ini pengujian Cawal.', 'Cawal native paste test'].includes(clipboard.readText())) clipboard.write(oldClipboard);
    app.exit(0);
  } catch (error) {
    console.error('FAIL:', error.stack);
    console.error('State:', JSON.stringify(dictation.snapshot()));
    console.error('Renderer errors:', errors);
    await capture('cawal-failure.png').catch(() => {});
    if (['Halo, ini pengujian Cawal.', 'Cawal native paste test'].includes(clipboard.readText())) clipboard.write(oldClipboard);
    app.exit(1);
  }
};
